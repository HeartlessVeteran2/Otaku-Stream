// Resolves SYSTEM against the platform setting. Separate from OtakuStreamTheme so callers that
// need to know which way it went — the activity, which has to match the system bar icons to it —
// can ask without reaching into the composition.
@Composable
fun ThemeMode.isDark(): Boolean = when (this) {
    ThemeMode.SYSTEM -> isSystemInDarkTheme()
    ThemeMode.DARK -> true
    ThemeMode.LIGHT -> false
}

@Composable
fun OtakuStreamTheme(themeMode: ThemeMode = ThemeMode.SYSTEM, content: @Composable () -> Unit) {
    MaterialTheme(
        colorScheme = if (themeMode.isDark()) OtakuDarkColors else OtakuLightColors,
        typography = OtakuTypography,
        shapes = OtakuShapes,
        content = content,
    )
}
